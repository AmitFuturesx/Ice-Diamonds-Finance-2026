// Generates src/orbit/styles/ice-dark.gen.css: for every rule in the Orbit styles that paints a light
// surface (white, light greys, pale tints), a html[data-theme='dark'] copy with the dark equivalent.
// Green stays green: the sidebar/login/green cards are skipped, and only light colors are mapped.
// Run after changing styles:  node scripts/gen-dark.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'orbit', 'styles')
const FILES = ['base.css', 'shell.css', 'board.css', 'widgets.css', 'kit.css', 'pages-crm.css', 'pages-a.css', 'rtl.css', 'ice-board.css', 'ice-invoices.css', 'ice-daily.css']

// light → dark (surfaces, borders, shadows)
const MAP = {
  white: 'var(--card)', '#fff': 'var(--card)', '#ffffff': 'var(--card)',
  // light greys
  '#fafcfc': '#1d272c', '#f6f9f9': '#1d272c', '#f4f7f8': '#1d272c', '#f3f7f8': '#222d33', '#f3f6f7': '#222d33', '#f1f5f6': '#222d33',
  '#f0f4f5': '#222d33', '#eef3f4': '#25313a', '#eef2f3': '#25313a', '#edf2f3': '#25313a', '#e9eff1': '#25313a', '#e8eef0': '#25313a',
  '#e4ecee': '#2b3841', '#e4ebed': '#2b3841', '#e3eaec': '#2b3841', '#e3e9ec': '#2b3841', '#e2e8ea': '#2b3841', '#dfe7ea': '#2e3b44', '#d9e2e5': '#34424c',
  // orange / peach
  '#fdf0dc': '#33281a', '#fdf1e2': '#33281a', '#fdf3e4': '#33281a', '#fdf3e6': '#33281a', '#fbefdc': '#33281a',
  '#fbe3c4': '#4a3518', '#fcdaa4': '#4a3518', '#f6d7a6': '#4a3518', '#f6d3a2': '#4a3518',
  // red
  '#fde8e6': '#3a2224', '#fdeae8': '#3a2224', '#fdecea': '#3a2224', '#fdeeed': '#3a2224', '#fbdcd9': '#4a2a2c',
  // purple
  '#f3e9fb': '#2c2338',
  // green tints (backgrounds only — the brand greens themselves are untouched)
  '#e3f2dd': '#1c2e20', '#e6f3e1': '#1c2e20', '#f4faf2': '#1c2e20', '#e9f6e5': '#1c2e20', '#edf7ea': '#1c2e20', '#dff0da': '#1f3524', '#ecf6e9': '#1c2e20', '#edf6ea': '#1c2e20',
  '#d7eed2': '#28432c', '#cfe8c8': '#2f5034', '#bfe0b6': '#2f5034',
  // teal / blue tints
  '#e3f0f4': '#16303a', '#e4f0f6': '#16303a', '#e3eff4': '#16303a'
}
// dark text that sits on pale tints → lighter, so it reads on the dark tints
const TEXT = { '#9a5a12': '#f0b56a', '#c4423b': '#f08a80', '#d4483f': '#f08a80', '#9a5a12;': '#f0b56a' }

// parts that sit on green or are already dark: leave them alone
const SKIP = /\.(nav|side|goal|profile|ice-login|ice-mbar|frame|toast|bulkbar|ice-bal-profit|ice-day-sum|ice-rep-month|ice-brand-mark|sv-|savings|team-card|member-tip|tk-tip|pf-row\.is-green)/

const hexRe = /#[0-9a-fA-F]{3,6}\b|\bwhite\b/g
const SURFACE_PROPS = /^(background|background-color|background-image|border|border-[a-z-]+|box-shadow|outline|outline-color|fill|stroke)$/

function mapValue(prop, value) {
  if (prop === 'color') {
    let changed = false
    const v = value.replace(hexRe, (h) => (TEXT[h.toLowerCase()] ? ((changed = true), TEXT[h.toLowerCase()]) : h))
    return changed ? v : null
  }
  if (!SURFACE_PROPS.test(prop)) return null
  let changed = false
  const v = value.replace(hexRe, (h) => {
    const k = h.toLowerCase()
    if (MAP[k]) {
      changed = true
      return MAP[k]
    }
    return h
  })
  return changed ? v : null
}

function strip(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '')
}

/** Tiny CSS walker: returns [{ media, selector, body }] (one level of @media/@supports, @layer unwrapped). */
function rules(css, media = null, out = []) {
  let i = 0
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open < 0) break
    const head = css.slice(i, open).trim()
    let depth = 1
    let j = open + 1
    while (j < css.length && depth) {
      if (css[j] === '{') depth++
      else if (css[j] === '}') depth--
      j++
    }
    const body = css.slice(open + 1, j - 1)
    if (head.startsWith('@media') || head.startsWith('@supports')) rules(body, head, out)
    else if (head.startsWith('@layer')) rules(body, media, out)
    else if (!head.startsWith('@')) out.push({ media, selector: head, body })
    i = j
  }
  return out
}

let outCss = `/* GENERATED by scripts/gen-dark.mjs — do not edit by hand. Dark copies of light surfaces. */\n`
let count = 0
for (const f of FILES) {
  const list = rules(strip(fs.readFileSync(path.join(dir, f), 'utf8')))
  for (const r of list) {
    const sels = r.selector.split(',').map((s) => s.trim()).filter(Boolean)
    if (sels.some((s) => SKIP.test(s))) continue
    if (sels.some((s) => s.startsWith(':root') || s.startsWith('html') || s.includes('@keyframes') || /^(from|to|\d+%)$/.test(s))) continue
    const decls = []
    for (const d of r.body.split(/;(?![^(]*\))/)) {
      const k = d.indexOf(':')
      if (k < 0) continue
      const prop = d.slice(0, k).trim()
      const value = d.slice(k + 1).trim()
      const v = mapValue(prop, value)
      if (v) decls.push(`  ${prop}: ${v};`)
    }
    if (!decls.length) continue
    const sel = sels.map((s) => `html[data-theme='dark'] ${s}`).join(',\n')
    const block = `${sel} {\n${decls.join('\n')}\n}\n`
    outCss += r.media ? `${r.media} {\n${block}}\n` : block
    count++
  }
}
fs.writeFileSync(path.join(dir, 'ice-dark.gen.css'), outCss)
console.log(`ice-dark.gen.css: ${count} rules`)
